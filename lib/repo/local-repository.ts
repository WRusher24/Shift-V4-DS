  /* ------------------------------------------------------------- workers */

  async listWorkers(): Promise<Worker[]> {
    return clone(getDb().workers).sort((a, b) => a.fullName.localeCompare(b.fullName, 'he'));
  }

  async getWorkerById(id: string): Promise<Worker | null> {
    return clone(getDb().workers.find((worker) => worker.id === id) ?? null);
  }

  async getWorkerByEmployeeId(employeeId: string): Promise<Worker | null> {
    const needle = employeeId.trim().toLowerCase();
    return clone(
      getDb().workers.find((worker) => worker.employeeId.trim().toLowerCase() === needle) ?? null,
    );
  }

  async getWorkerByEmoji(emoji: string): Promise<Worker | null> {
    const needle = emoji.trim();
    return clone(getDb().workers.find((worker) => worker.emoji.trim() === needle) ?? null);
  }

  async insertWorker(worker: Worker): Promise<Worker> {
    return mutate((db) => {
      db.workers.push(worker);
      return clone(worker);
    });
  }

  async updateWorker(id: string, patch: Partial<Omit<Worker, 'id' | 'createdAt'>>): Promise<Worker> {
    return mutate((db) => {
      const index = db.workers.findIndex((worker) => worker.id === id);
      if (index === -1) throw new RepositoryError('not_found', 'Worker not found', 404);
      db.workers[index] = { ...db.workers[index], ...patch, id };
      return clone(db.workers[index]);
    });
  }

  async deleteWorker(id: string): Promise<void> {
    await mutate((db) => {
      db.workers = db.workers.filter((worker) => worker.id !== id);
    });
  }


/**
 * LocalRepository — zero-configuration persistence adapter.
 *
 * Backs the entire platform with a single JSON document on disk
 * (`.data/shift-db.json` by default). This is what makes the project runnable
 * with `npm run dev` and no cloud account whatsoever, and it is what the
 * automated tests exercise.
 *
 * Design notes
 * ------------
 * - The whole document is loaded once per process and cached on `globalThis`
 *   so Next.js hot reloads do not lose state.
 * - Mutations are serialised through a promise queue: two concurrent HTTP
 *   requests can never interleave a read-modify-write cycle.
 * - Writes are atomic (`write temp -> rename`) so a crash mid-save cannot
 *   corrupt the store.
 * - A document written by an older schema version is discarded rather than
 *   migrated. It is demo data, and discarding it re-triggers the automatic
 *   seed, which is exactly the desired behaviour after a schema change.
 * - If the filesystem is read-only (serverless), the adapter degrades to a
 *   purely in-memory store and logs a warning instead of throwing. Production
 *   deployments are expected to set `DATABASE_URL`.
 */


  async listPalletLogs(filter?: PalletLogFilter): Promise<PalletLog[]> {
    let pallets = clone(getDb().palletLogs);

    if (filter?.productId) pallets = pallets.filter((pallet) => pallet.productId === filter.productId);
    if (filter?.from || filter?.to) {
      pallets = pallets.filter((pallet) => inRange(pallet.createdAt, filter.from, filter.to));
    }

    if (filter?.lineId) {
      const lineBatchIds = new Set(
        getDb()
          .batches.filter((batch) => batch.lineId === filter.lineId)
          .map((batch) => batch.id),
      );
      pallets = pallets.filter((pallet) => lineBatchIds.has(pallet.batchId));
    }

    pallets.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
    if (filter?.limit && filter.limit > 0) pallets = pallets.slice(0, filter.limit);
    return pallets;
  }


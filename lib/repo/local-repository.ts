  /* --------------------------------------------------------------- races */

  async listRaces(filter?: RaceFilter): Promise<Race[]> {
    let races = clone(getDb().races);
    if (filter?.status) races = races.filter((race) => race.status === filter.status);
    if (filter?.isPrimary !== undefined) races = races.filter((race) => race.isPrimary === filter.isPrimary);
    return races.sort((a, b) => new Date(b.startAt).getTime() - new Date(a.startAt).getTime());
  }

  async getRaceById(id: string): Promise<Race | null> {
    return clone(getDb().races.find((race) => race.id === id) ?? null);
  }

  async getPrimaryRace(): Promise<Race | null> {
    const race = getDb()
      .races.filter((candidate) => candidate.status === 'ACTIVE' && candidate.isPrimary)
      .sort((a, b) => new Date(b.startAt).getTime() - new Date(a.startAt).getTime())[0];
    return clone(race ?? null);
  }

  async insertRace(race: Race): Promise<Race> {
    return mutate((db) => {
      db.races.push(race);
      return clone(race);
    });
  }

  async updateRace(id: string, patch: Partial<Omit<Race, 'id' | 'createdAt'>>): Promise<Race> {
    return mutate((db) => {
      const index = db.races.findIndex((race) => race.id === id);
      if (index === -1) throw new RepositoryError('not_found', 'Race not found', 404);
      db.races[index] = { ...db.races[index], ...patch, id };
      return clone(db.races[index]);
    });
  }

  async setPrimaryRace(id: string): Promise<Race | null> {
    return mutate((db) => {
      const target = db.races.find((race) => race.id === id);
      if (!target) throw new RepositoryError('not_found', 'Race not found', 404);

      db.races = db.races.map((race) => {
        if (race.id === id) return { ...race, isPrimary: true };
        // Only an ACTIVE race can hold the flag, so stale flags are cleared too.
        return race.isPrimary ? { ...race, isPrimary: false } : race;
      });

      return clone(db.races.find((race) => race.id === id) ?? null);
    });
  }

  async clearPrimaryRace(): Promise<void> {
    await mutate((db) => {
      db.races = db.races.map((race) => (race.isPrimary ? { ...race, isPrimary: false } : race));
    });
  }

  /**
   * Removes a race together with its own ledger rows, mirroring the
   * `ON DELETE CASCADE` on `point_awards.race_id`. No other race, batch or
   * pallet is touched — race attribution exists only in the award rows.
   */
  async deleteRace(id: string): Promise<void> {
    await mutate((db) => {
      db.races = db.races.filter((race) => race.id !== id);
      db.pointAwards = db.pointAwards.filter((award) => award.raceId !== id);
      db.raceProductPoints = db.raceProductPoints.filter((row) => row.raceId !== id);
    });
  }

  async listExpiredActiveRaces(now: string): Promise<Race[]> {
    const threshold = new Date(now).getTime();
    return clone(
      getDb().races.filter(
        (race) =>
          race.status === 'ACTIVE' && race.endAt !== null && new Date(race.endAt).getTime() <= threshold,
      ),
    );
  }


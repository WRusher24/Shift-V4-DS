  /* ------------------------------------------------------------- batches */

  async listBatches(filter?: BatchFilter): Promise<Batch[]> {
    let batches = clone(getDb().batches);

    if (filter?.status) batches = batches.filter((batch) => batch.status === filter.status);
    if (filter?.lineId) batches = batches.filter((batch) => batch.lineId === filter.lineId);
    if (filter?.productId) batches = batches.filter((batch) => batch.productId === filter.productId);
    if (filter?.from || filter?.to) {
      batches = batches.filter((batch) => inRange(batch.startedAt, filter.from, filter.to));
    }

    batches.sort((a, b) => new Date(b.startedAt).getTime() - new Date(a.startedAt).getTime());
    if (filter?.limit && filter.limit > 0) batches = batches.slice(0, filter.limit);
    return batches;
  }

